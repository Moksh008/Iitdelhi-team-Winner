/**
 * Builds and signs shared/scam-intel-feed.json.
 *
 *   node tools/sign-intel-feed.mjs [entries.json]
 *
 * entries.json (optional) is a list of { type: 'phone'|'vpa', value, sources, reports }.
 * Without it, the demo feed is built from the scripted scenarios whose caller is
 * marked as reported. Those numbers are fictional and the feed says so.
 *
 * The private key is created on first run in tools/keys/ (git-ignored) and the
 * matching public key is written to src/engine/intelFeedKey.js, where the app pins it.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SCENARIOS } from '../src/engine/scenarios.js';
import { hashPhone, hashVpa, verifyIntelFeed } from '../src/engine/intelFeed.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const keyDir = join(root, 'tools', 'keys');
const privatePath = join(keyDir, 'intel-feed-private.jwk.json');
const publicModule = join(root, 'src', 'engine', 'intelFeedKey.js');
const feedPath = join(root, 'shared', 'scam-intel-feed.json');
const VALID_DAYS = 365;

async function loadOrCreateKeys() {
  if (existsSync(privatePath)) {
    const jwk = JSON.parse(readFileSync(privatePath, 'utf8'));
    const privateKey = await crypto.subtle.importKey('jwk', jwk, { name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign']);
    const { d, ...publicJwk } = jwk;
    return { privateKey, publicJwk: { ...publicJwk, key_ops: ['verify'] } };
  }
  const pair = await crypto.subtle.generateKey({ name: 'ECDSA', namedCurve: 'P-256' }, true, ['sign', 'verify']);
  mkdirSync(keyDir, { recursive: true });
  writeFileSync(privatePath, JSON.stringify(await crypto.subtle.exportKey('jwk', pair.privateKey), null, 2));
  const publicJwk = await crypto.subtle.exportKey('jwk', pair.publicKey);
  console.log(`Created a new signing key in ${privatePath} (keep it secret, never commit it).`);
  return { privateKey: pair.privateKey, publicJwk };
}

function demoEntries() {
  const entries = [];
  for (const scenario of SCENARIOS) {
    if (!scenario.caller?.isFlagged) continue;
    entries.push({ type: 'phone', value: scenario.caller.number, sources: 2, reports: 3 });
    entries.push({ type: 'vpa', value: scenario.suggestedPayment.payeeVPA, sources: 2, reports: 3 });
  }
  return entries;
}

const input = process.argv[2] ? JSON.parse(readFileSync(process.argv[2], 'utf8')) : null;
const raw = input || demoEntries();
const entries = [];
for (const item of raw) {
  const sha256 = item.type === 'phone' ? await hashPhone(item.value) : await hashVpa(item.value);
  entries.push({ type: item.type, sha256, sources: item.sources ?? 1, reports: item.reports ?? 1 });
}

const issued = new Date();
const payload = {
  version: 1,
  issued_at: issued.toISOString(),
  expires_at: new Date(issued.getTime() + VALID_DAYS * 24 * 60 * 60 * 1000).toISOString(),
  min_sources: 2,
  note: input
    ? 'Hashed numbers and UPI IDs from public reports.'
    : 'DEMO feed: fictional numbers and UPI IDs from the scripted scenarios, not real reports.',
  entries,
};

const { privateKey, publicJwk } = await loadOrCreateKeys();
const payloadJson = JSON.stringify(payload);
const signature = new Uint8Array(await crypto.subtle.sign({ name: 'ECDSA', hash: 'SHA-256' }, privateKey, new TextEncoder().encode(payloadJson)));

writeFileSync(feedPath, `${JSON.stringify({ payload_json: payloadJson, signature: Buffer.from(signature).toString('base64') }, null, 2)}\n`);
writeFileSync(publicModule, `// Generated by tools/sign-intel-feed.mjs. The app trusts only feeds signed by the matching private key.
export const INTEL_FEED_PUBLIC_KEY = ${JSON.stringify({ kty: publicJwk.kty, crv: publicJwk.crv, x: publicJwk.x, y: publicJwk.y }, null, 2)};
`);

const check = await verifyIntelFeed(JSON.parse(readFileSync(feedPath, 'utf8')), {
  publicKey: { kty: publicJwk.kty, crv: publicJwk.crv, x: publicJwk.x, y: publicJwk.y },
});
if (!check.feed) throw new Error(`signed feed failed verification: ${check.error}`);
console.log(`Signed ${entries.length} entries (${check.feed.size} usable after corroboration) -> ${feedPath}`);
